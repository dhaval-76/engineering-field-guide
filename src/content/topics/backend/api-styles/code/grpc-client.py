import grpc
from shop.orders.v1 import orders_pb2, orders_pb2_grpc   # generated by grpcio-tools

channel = grpc.secure_channel(
    "orders.internal:443",
    grpc.ssl_channel_credentials(),
    options=[("grpc.lb_policy_name", "round_robin")],
)
stub = orders_pb2_grpc.OrderServiceStub(channel)

try:
    order = stub.GetOrder(orders_pb2.GetOrderRequest(order_id="A-1001"), timeout=0.3)  # deadline
    print(order.status, order.total_cents)
except grpc.RpcError as e:
    if e.code() == grpc.StatusCode.NOT_FOUND:
        print("no such order")
    elif e.code() in (grpc.StatusCode.DEADLINE_EXCEEDED, grpc.StatusCode.UNAVAILABLE):
        print("retry with backoff if idempotent")
    else:
        raise

for event in stub.WatchOrder(orders_pb2.WatchOrderRequest(order_id="A-1001")):   # server streaming
    print("status", event.status)
