import { useCallback, useEffect, useRef, useState, type KeyboardEvent } from 'react';
import './palette.css';

interface PagefindResultData {
  url: string;
  excerpt: string;
  meta: { title?: string; track?: string };
  sub_results?: { title: string; url: string; excerpt: string }[];
}
interface Pagefind {
  init: () => Promise<void>;
  search: (q: string) => Promise<{ results: { data: () => Promise<PagefindResultData> }[] }>;
}

interface Hit {
  url: string;
  title: string;
  track?: string | undefined;
  excerpt: string;
  section?: string | undefined;
}

export default function CommandPalette({ base }: { base: string }) {
  const dialog = useRef<HTMLDialogElement>(null);
  const input = useRef<HTMLInputElement>(null);
  // One shared load: every keystroke awaits the same promise instead of racing its own import.
  const pagefind = useRef<Promise<Pagefind> | null>(null);
  const loadIndex = useCallback(() => {
    pagefind.current ??= (async () => {
      const mod = (await import(/* @vite-ignore */ `${base}pagefind/pagefind.js`)) as Pagefind;
      await mod.init();
      return mod;
    })();
    return pagefind.current;
  }, [base]);
  const [query, setQuery] = useState('');
  const [hits, setHits] = useState<Hit[]>([]);
  const [active, setActive] = useState(0);
  const [status, setStatus] = useState<'idle' | 'loading' | 'unavailable'>('idle');

  const open = useCallback(() => {
    dialog.current?.showModal();
    input.current?.select();
    loadIndex().catch(() => setStatus('unavailable'));
  }, [loadIndex]);

  useEffect(() => {
    const onClick = (e: MouseEvent) => {
      if ((e.target as Element).closest('[data-search-open]')) open();
    };
    const onKey = (e: globalThis.KeyboardEvent) => {
      const el = e.target as HTMLElement;
      const typing = el.isContentEditable || /^(INPUT|TEXTAREA|SELECT)$/.test(el.tagName);
      if ((e.key === 'k' && (e.metaKey || e.ctrlKey)) || (e.key === '/' && !typing)) {
        e.preventDefault();
        open();
      }
    };
    document.addEventListener('click', onClick);
    document.addEventListener('keydown', onKey);
    return () => {
      document.removeEventListener('click', onClick);
      document.removeEventListener('keydown', onKey);
    };
  }, [open]);

  useEffect(() => {
    let cancelled = false;
    const q = query.trim();
    if (!q) {
      setHits([]);
      return;
    }
    const timer = setTimeout(async () => {
      let pf: Pagefind;
      try {
        setStatus('loading');
        pf = await loadIndex();
      } catch {
        pagefind.current = null;
        setStatus('unavailable');
        return;
      }
      const res = await pf.search(q);
      if (cancelled) return;
      setStatus('idle');
      const data = await Promise.all(res.results.slice(0, 10).map((r) => r.data()));
      if (cancelled) return;
      const out: Hit[] = [];
      for (const d of data) {
        const sub = d.sub_results?.find((s) => s.url !== d.url);
        out.push({
          url: sub?.url ?? d.url,
          title: d.meta.title ?? d.url,
          track: d.meta.track,
          section: sub?.title,
          excerpt: (sub ?? d).excerpt,
        });
      }
      setHits(out);
      setActive(0);
    }, 120);
    return () => {
      cancelled = true;
      clearTimeout(timer);
    };
  }, [query, loadIndex]);

  const onKeyDown = (e: KeyboardEvent<HTMLInputElement>) => {
    if (e.key === 'ArrowDown') setActive((a) => Math.min(hits.length - 1, a + 1));
    else if (e.key === 'ArrowUp') setActive((a) => Math.max(0, a - 1));
    else if (e.key === 'Enter' && hits[active]) location.href = hits[active]!.url;
    else return;
    e.preventDefault();
  };

  return (
    <dialog
      ref={dialog}
      className="palette"
      aria-label="Search"
      onClick={(e) => e.target === dialog.current && dialog.current?.close()}
      // Focus can stay in the hidden input after closing, which would swallow keyboard shortcuts.
      onClose={() => input.current?.blur()}
    >
      <div className="palette-box">
        <div className="palette-input">
          <svg viewBox="0 0 24 24" className="icon" aria-hidden="true">
            <path d="M11 4a7 7 0 1 1 0 14 7 7 0 0 1 0-14zM20 20l-4-4" />
          </svg>
          <input
            ref={input}
            type="search"
            placeholder="Search topics, concepts, questions…"
            value={query}
            onChange={(e) => setQuery(e.target.value)}
            onKeyDown={onKeyDown}
            aria-controls="palette-results"
            aria-activedescendant={hits[active] ? `hit-${active}` : undefined}
            autoComplete="off"
            spellCheck={false}
          />
          <kbd>Esc</kbd>
        </div>
        <ul id="palette-results" role="listbox" className="palette-results">
          {status === 'unavailable' && (
            <li className="palette-empty">
              Search index not found. It is generated by <code>npm run build</code>.
            </li>
          )}
          {status !== 'unavailable' && query.trim() && hits.length === 0 && (
            <li className="palette-empty">{status === 'loading' ? 'Loading…' : 'No matches.'}</li>
          )}
          {!query.trim() && (
            <li className="palette-empty">
              Try <em>consistent hashing</em>, <em>volatile</em>, <em>LRU</em> or{' '}
              <em>idempotency</em>.
            </li>
          )}
          {hits.map((h, i) => (
            <li key={h.url} id={`hit-${i}`} role="option" aria-selected={i === active}>
              <a href={h.url} onMouseEnter={() => setActive(i)}>
                <span className="palette-title">
                  {h.title}
                  {h.section && <span className="palette-section"> › {h.section}</span>}
                </span>
                {h.track && <span className="palette-track">{h.track}</span>}
                <span className="palette-excerpt" dangerouslySetInnerHTML={{ __html: h.excerpt }} />
              </a>
            </li>
          ))}
        </ul>
      </div>
    </dialog>
  );
}
